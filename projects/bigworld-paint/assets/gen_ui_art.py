COLS, ROWS, CELL = 16, 14, 8


def font_pixels():
    """128 x 112 rows of 0 (paper) / 3 (ink)."""
    px = [[0] * (COLS * CELL) for _ in range(ROWS * CELL)]
    for code in range(32, 128):
        rows = GLYPHS[chr(code)]
        assert 7 <= len(rows) <= 8 and all(len(r) == 5 for r in rows), chr(code)
        i = code - 32
        ox, oy = (i % COLS) * CELL, (i // COLS) * CELL
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    px[oy + y][ox + 1 + x] = 3
    return px


def frame_pixels():
    """24 x 24 rows of shades 0..3: the edge by its distance from the rim."""
    n = 24
    px = [[0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            d = min(x, y, n - 1 - x, n - 1 - y)
            px[y][x] = 3 if d == 0 else 2 if d == 1 else 1 if d == 2 else 0
            # clipped corners: the outermost corner pixel is paper
            if (x in (0, n - 1)) and (y in (0, n - 1)):
                px[y][x] = 0
    return px


def write(out_dir):
    font = font_pixels()
    write_png_indexed(os.path.join(out_dir, "font.png"), COLS * CELL,
                      ROWS * CELL, font, SHADES)
    frame = frame_pixels()
    write_png_indexed(os.path.join(out_dir, "frame.png"), 24, 24, frame, SHADES)
    print("wrote font.png + frame.png ->", os.path.normpath(out_dir))


def main(argv):
    if argv:
        for d in argv:
            write(d)
        return 0
    write(HERE)
    write(os.path.join(HERE, "..", "..", "vm-boxtest", "assets"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
