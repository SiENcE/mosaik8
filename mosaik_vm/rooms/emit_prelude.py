def _pnc_tick(has_trig, has_ent, has_doors, bpos):
    """The POINT-AND-CLICK per-frame tick (W7j), which is NOT the topdown one
    with another move in it.

    The reference VM's `src/states/pointnclick.c`'s update, composed here because the two
    things it does beyond moving - pick the hover pose, and run what the cursor
    is over on A - read the trigger table and the actor list, which vm.player
    cannot see. Three differences from tick_topdown, each from the reference:

    * NO AUTOMATIC TRIGGER SCAN. It calls `trigger_at_intersection` (a pure
      query) and never `trigger_activate_at_intersection`, so a rect fires only
      when A is pressed over it. `trigger.update(...)` is deliberately absent.
    * THE HOVER POSE. `ANIM_CURSOR` / `ANIM_CURSOR_HOVER` are engine animations
      0 and 1, which our clip tables reach as FACINGS 0 (down) and 3 (right) -
      that is what `animationMapBySpriteType` + `toEngineOrder` map them to for
      BOTH a `cursor` sprite (authored animations 0 and 1) and an ordinary
      multi-direction one (idle down and idle right). vm.canim pins the clip
      STATE, so only the facing is published here.
    * A INTERACTS WITH THE OVERLAP, actor first and then trigger, never with a
      facing probe. The actor half is `entity.update()` itself, in the cursor
      mode the dispatch arm switched on; the trigger half is below it, and it
      is skipped when an actor took the press (the reference's `else if`).

    A DOOR still runs its contact scan: `[[door]]` is our own verb and has no
    counterpart in the reference's model (the reference engine spells a door as a trigger
    whose script changes scene, which here fires on the click). A hand-authored
    point-and-click room that places one means it.
    """
    L = ["    function tick_pointnclick() {",
         "        player.update_pointnclick()"]
    L.append("        var ah: u8 = 0          -- an actor is under the cursor")
    L.append("        var ct: u8 = 255        -- ...and which trigger is")
    if has_ent:
        L.append("        ah = entity.probe()")
    if has_trig:
        L.append("        ct = trigger.hit_script(%s, PW, PH)" % bpos)
    L += ["        if ah == 1 or ct != 255 {",
          "            player.set_face(3)     -- ANIM_CURSOR_HOVER",
          "        } else {",
          "            player.set_face(0)     -- ANIM_CURSOR",
          "        }"]
    if has_doors:
        L.append("        door.update(%s, PW, PH)" % bpos)
    if has_ent:
        L.append("        entity.update()")
    if has_trig:
        L += ["        if ah == 0 and ct != 255 {",
              "            if core.interact_pressed() == 1 {",
              "                trigger.interact(ct)",
              "            }",
              "        }"]
    L += ["    }", ""]
    return L
